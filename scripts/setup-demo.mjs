#!/usr/bin/env node
/**
 * Writes a .env.local wired for demo mode, generating the two internal
 * secrets. Everything except the Supabase keys is filled in — those are the
 * one thing that has to come from your own project.
 *
 *   node scripts/setup-demo.mjs
 *   node scripts/setup-demo.mjs --url https://xxx.supabase.co --anon ey... --service ey...
 */
import crypto from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'

const args = process.argv.slice(2)
function arg(name) {
  const i = args.indexOf(`--${name}`)
  return i !== -1 ? args[i + 1] : ''
}

const target = path.join(process.cwd(), '.env.local')
if (fs.existsSync(target) && !args.includes('--force')) {
  console.error('.env.local already exists. Pass --force to overwrite it.')
  process.exit(1)
}

const secret = () => crypto.randomBytes(32).toString('hex')

const contents = `# Generated by scripts/setup-demo.mjs — demo mode, no developer apps needed.

# Simulated platforms. Unset this (and fill in the app credentials below)
# when you're ready to post for real.
NEXT_PUBLIC_PLATFORM_MOCK=1

# ---- Supabase (the one thing you must supply) ----
# Project Settings -> API in your Supabase dashboard.
NEXT_PUBLIC_SUPABASE_URL=${arg('url')}
NEXT_PUBLIC_SUPABASE_ANON_KEY=${arg('anon')}
SUPABASE_SERVICE_ROLE_KEY=${arg('service')}

# ---- Generated secrets ----
OAUTH_STATE_SECRET=${secret()}
INTERNAL_API_SECRET=${secret()}
CRON_SECRET=${secret()}

# ---- Not needed in demo mode ----
STRIPE_SECRET_KEY=
STRIPE_WEBHOOK_SECRET=
NEXT_PUBLIC_STRIPE_PRICE_STARTER=
NEXT_PUBLIC_STRIPE_PRICE_CREATOR=
NEXT_PUBLIC_STRIPE_PRICE_PRO=

X_CLIENT_ID=
X_CLIENT_SECRET=
LINKEDIN_CLIENT_ID=
LINKEDIN_CLIENT_SECRET=
LINKEDIN_API_VERSION=202506
`

fs.writeFileSync(target, contents)

const missing = ['url', 'anon', 'service'].filter((k) => !arg(k))
console.log('Wrote .env.local with freshly generated secrets.')

if (missing.length) {
  console.log(`
Still needed — create a free project at https://supabase.com/dashboard, then
copy these from Project Settings -> API into .env.local:

  NEXT_PUBLIC_SUPABASE_URL        Project URL
  NEXT_PUBLIC_SUPABASE_ANON_KEY   anon / public key
  SUPABASE_SERVICE_ROLE_KEY       service_role key (keep it secret)

Then, in the SQL editor, run these two files in order:

  supabase/schema.sql
  supabase/migrations/0002_profile_trigger_and_indexes.sql

And create a public Storage bucket named  post-media

Finally:  npm run dev`)
} else {
  console.log('\nRun the two SQL files, create the post-media bucket, then: npm run dev')
}
